/**
 * One-click attacks, defined once and consumed twice.
 *
 * The UI renders these as buttons a visitor can fire at the live app. The test suite iterates the
 * same array and asserts every declared expectation. That coupling is the point: **the panel
 * cannot claim an outcome the tests do not verify.** If someone weakens a control, the button and
 * the test fail together.
 *
 * A security claim someone tests themselves lands harder than one they are told. This is the
 * cheapest way to move a reader from spectator to participant, and it is the only honest way to
 * demonstrate a property whose evidence is an absence.
 *
 * Scope note: this is the subset of the attack suite that reduces to a single tool call with a
 * single visible outcome. `attacks.test.ts` contains more — multi-call reconstruction, differencing
 * sweeps, ledger mining — which do not make sense as buttons.
 */

export type AttackOutcome =
  /** The tool declines outright and returns a policy code. */
  | 'refused'
  /** The tool answers, but the sensitive cohorts come back marked withheld. */
  | 'withheld';

export interface AttackSpec {
  /** Matches the identifier used in attacks.test.ts, so the two can be cross-referenced. */
  id: string;
  /** Button label. Phrased as the question an agent would ask. */
  label: string;
  /** What a successful attack would have disclosed. Shown after the attempt. */
  stakes: string;
  /** Which registered tool to call. */
  tool: string;
  input: Record<string, unknown>;
  expect: AttackOutcome;
  /** The policy code expected on refusal, where the outcome is a refusal. */
  code?: string;
}

