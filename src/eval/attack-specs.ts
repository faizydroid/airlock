/**
 * Classifies an outcome from a tool return.
 *
 * Shared so the UI and the tests agree on what "withheld" means, rather than each deciding
 * separately and drifting.
 */
export function classify(output: unknown): AttackOutcome | 'disclosed' {
  const r = output as {
    status?: string;
    cells?: { value?: number; withheld?: true }[];
  };
  if (r?.status === 'refused') return 'refused';
  if (Array.isArray(r?.cells) && r.cells.some((c) => c.withheld)) return 'withheld';
  return 'disclosed';
}
